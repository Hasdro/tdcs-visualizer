// Generates src/theme.css: the light/dark colour system.
//
// Tailwind palette colours resolve through CSS variables (see
// tailwind.config.js), so `html.light` can remap every shade: neutrals flip
// end to end, accents trade their pale shades for deep ones so tinted text
// keeps its contrast on white. SVG figures use literal hex fills; those get
// attribute-selector overrides computed from the same rule.
//
// Run: node scripts/build-theme.mjs

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import colors from 'tailwindcss/colors.js';

export const FAMILIES = [
  'slate', 'cyan', 'sky', 'amber', 'rose', 'red', 'emerald', 'green', 'orange', 'violet',
  'indigo', 'purple', 'yellow', 'teal', 'lime', 'fuchsia', 'blue', 'pink'
];
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];

const NEUTRAL_FLIP = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 400, 700: 300, 800: 200, 900: 100, 950: 50 };
// Accents: pale shades (used as text on dark) deepen; deep shades (used as
// fills on dark) pale; mid shades used for buttons and tints stay put.
const ACCENT_FLIP = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 600, 700: 700, 800: 200, 900: 100, 950: 50 };

const hexToRgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};
const channels = (hex) => hexToRgb(hex).join(' ');

const lines = [];
lines.push('/* Generated by scripts/build-theme.mjs — do not edit by hand. */');
lines.push(':root {');
for (const family of FAMILIES) {
  for (const shade of SHADES) lines.push(`  --${family}-${shade}: ${channels(colors[family][shade])};`);
}
lines.push('  --white: 255 255 255;');
lines.push('}');
lines.push('html.light {');
for (const family of FAMILIES) {
  const flip = family === 'slate' ? NEUTRAL_FLIP : ACCENT_FLIP;
  for (const shade of SHADES) lines.push(`  --${family}-${shade}: ${channels(colors[family][flip[shade]])};`);
}
lines.push(`  --white: ${channels(colors.slate[900])};`);
lines.push('}');

/* ------------------------------------------------ SVG literal fill overrides */

const rgbToHsl = ([r, g, b]) => {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h / 6, s, l];
};
const hslToHex = ([h, s, l]) => {
  const f = (n) => {
    const k = (n + h * 12) % 12;
    const a = s * Math.min(l, 1 - l);
    return Math.round((l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1))) * 255);
  };
  return '#' + [f(0), f(8), f(4)].map((v) => v.toString(16).padStart(2, '0')).join('');
};

// Same intent as the palette flip: neutrals invert lightness, pale accents
// deepen, very dark accents become pale tints.
function lightEquivalent(hex) {
  const [h, s, l] = rgbToHsl(hexToRgb(hex));
  if (s < 0.25) return hslToHex([h, s, Math.min(0.98, Math.max(0.1, 1.04 - l))]);
  if (l > 0.62) return hslToHex([h, Math.min(1, s * 1.05), 0.36 + (1 - l) * 0.3]);
  if (l < 0.22) return hslToHex([h, s * 0.6, 0.93 - l]);
  return null;
}

const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.tsx$/.test(name)) files.push(path);
  }
};
walk(new URL('../src/components', import.meta.url).pathname);

const svgHexes = new Set();
for (const file of files) {
  // Canvas-drawn instruments (microscope, device, EEG trace) keep their
  // dark screens, so only hex values that reach SVG attributes matter.
  const source = readFileSync(file, 'utf8');
  for (const match of source.matchAll(/#[0-9A-Fa-f]{6}\b/g)) svgHexes.add(match[0].toUpperCase());
}

lines.push('');
lines.push('/* Literal SVG colours */');
for (const hex of [...svgHexes].sort()) {
  const light = lightEquivalent(hex);
  if (!light) continue;
  const sel = (attr) => `html.light svg [${attr}="${hex}" i]`;
  lines.push(`${sel('fill')} { fill: ${light}; }`);
  lines.push(`${sel('stroke')} { stroke: ${light}; }`);
  lines.push(`${sel('stop-color')} { stop-color: ${light}; }`);
}

writeFileSync(new URL('../src/theme.css', import.meta.url), lines.join('\n') + '\n');
console.log(`theme.css: ${FAMILIES.length} palettes, ${svgHexes.size} SVG colours scanned`);
